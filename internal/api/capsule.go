func (s *Server) capsule(w http.ResponseWriter, r *http.Request) {
	f, ok := s.filter(w, r)
	if !ok {
		return
	}
	f.Limit = capsuleRows
	ctx := r.Context()
	d := capsuleData{Rows: capsuleRows, From: time.UnixMilli(f.From.UnixMilli()).UTC().Format(time.RFC3339), To: time.UnixMilli(f.To.UnixMilli()).UTC().Format(time.RFC3339)}
	var err error
	if d.Summary, err = s.cfg.Store.Summary(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.Devices, err = s.cfg.Store.Devices(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.Flows, err = s.cfg.Store.Flows(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.DNS, err = s.cfg.Store.DNS(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.WiFi, err = s.cfg.Store.WiFi(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	rep, err := s.cfg.Store.Anomalies(ctx, f)
	if err != nil {
		s.fail(w, err)
		return
	}
	d.Anomalies = rep.Anomalies
	if d.Notes, err = s.cfg.Store.Annotations(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.Bookmarks, err = s.cfg.Store.Bookmarks(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	for _, c := range []struct {
		name string
		n    int
	}{{"devices", len(d.Devices)}, {"connections", len(d.Flows)}, {"DNS", len(d.DNS)}, {"Wi-Fi", len(d.WiFi)}, {"notes", len(d.Notes)}, {"bookmarks", len(d.Bookmarks)}} {
		if c.n >= capsuleRows {
			d.Truncated = append(d.Truncated, c.name)
		}
	}
	// Render first: a template error must be an error, not half a report.
	var buf bytes.Buffer
	if err := capsuleTpl.Execute(&buf, d); err != nil {
		s.fail(w, err)
		return
	}
	s.addCapsulePlayer(r.Context(), &buf, f)
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	w.Header().Set("Content-Disposition", "attachment; filename=netgraph-capsule.html")
	_, _ = w.Write(buf.Bytes())
}

