package api

import (
	"bytes"
	"html/template"
	"net/http"
	"time"

	"github.com/xen0bit/netgraph/internal/model"
)

type capsuleData struct {
	From, To  string
	Summary   *model.Summary
	Devices   []model.Device
	Flows     []model.Flow
	DNS       []model.DNSQuery
	WiFi      []model.WiFiNetwork
	Anomalies []model.Anomaly
	Notes     []model.Annotation
	Bookmarks []model.Bookmark
	Truncated []string
	Rows      int
}

// capsuleRows caps each table. The report says so when it hits the cap.
const capsuleRows = 500

var capsuleTpl = template.Must(template.New("capsule").Funcs(template.FuncMap{
	"when":  func(ms int64) string { return time.UnixMilli(ms).UTC().Format("2006-01-02 15:04:05Z") },
	"bytes": model.FormatBytes,
}).Parse(`<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>netgraph time capsule</title>
<style>
body{font:14px/1.45 system-ui,sans-serif;margin:24px;color:#111;background:#fff}
h1{font-size:22px;margin:0 0 4px}h2{font-size:16px;margin:22px 0 6px}
.muted{color:#666}.mono{font-family:ui-monospace,monospace}
table{border-collapse:collapse;width:100%;font-size:12px}th,td{text-align:left;padding:3px 6px;border-bottom:1px solid #ddd}
th{background:#f5f5f5}ul{padding-left:18px}
@media print{body{margin:0}}
</style></head><body>
<h1>netgraph time capsule</h1>
<p class="muted">{{.From}} → {{.To}} · generated by netgraph</p>
{{with .Summary}}<p><b>{{.Devices}}</b> devices · <b>{{.Flows}}</b> connections · <b>{{.DNSQueries}}</b> lookups · ↑{{bytes .BytesOut}} ↓{{bytes .BytesIn}}</p>{{end}}
{{if .Anomalies}}<h2>Anomalies</h2><ul>{{range .Anomalies}}<li><b>{{.Severity}}</b> {{.Kind}} — {{.Summary}}</li>{{end}}</ul>{{end}}
{{if .Devices}}<h2>Devices</h2><table><thead><tr><th>Device</th><th>MAC</th><th>Addresses</th><th>Hostnames</th><th>Sent</th><th>Received</th></tr></thead><tbody>
{{range .Devices}}<tr><td>{{.Label}}</td><td class="mono">{{.MAC}}</td><td class="mono">{{range $i,$v := .IPs}}{{if $i}}, {{end}}{{$v}}{{end}}</td><td>{{range $i,$v := .Hostnames}}{{if $i}}, {{end}}{{$v}}{{end}}</td><td>{{bytes .BytesOut}}</td><td>{{bytes .BytesIn}}</td></tr>{{end}}
</tbody></table>{{end}}
{{if .Flows}}<h2>Connections</h2><table><thead><tr><th>Opened (UTC)</th><th>Direction</th><th>Device</th><th>Remote</th><th>Name</th><th>Sent</th><th>Received</th></tr></thead><tbody>
{{range .Flows}}<tr><td>{{when .FirstSeen}}</td><td>{{.Direction}}</td><td>{{.DeviceName}}</td><td class="mono">{{.RemoteIP}}:{{.RemotePort}}/{{.Proto}}</td><td>{{.Name}}</td><td>{{bytes .BytesOut}}</td><td>{{bytes .BytesIn}}</td></tr>{{end}}
</tbody></table>{{end}}
{{if .DNS}}<h2>DNS</h2><table><thead><tr><th>Time (UTC)</th><th>Device</th><th>Name</th><th>Type</th><th>RCode</th></tr></thead><tbody>
{{range .DNS}}<tr><td>{{when .TS}}</td><td>{{.DeviceName}}</td><td>{{.QName}}</td><td>{{.QType}}</td><td>{{.RCode}}</td></tr>{{end}}
</tbody></table>{{end}}
{{if .WiFi}}<h2>Wi-Fi</h2><table><thead><tr><th>SSID</th><th>BSSID</th><th>Security</th><th>Channel</th><th>Clients</th></tr></thead><tbody>
{{range .WiFi}}<tr><td>{{.SSID}}</td><td class="mono">{{.BSSID}}</td><td>{{.Security}}</td><td>{{.Channel}}</td><td>{{.Clients}}</td></tr>{{end}}
</tbody></table>{{end}}
{{if .Notes}}<h2>Notes</h2><ul>{{range .Notes}}<li><span class="muted">{{when .TS}}</span> {{.Text}}</li>{{end}}</ul>{{end}}
{{if .Bookmarks}}<h2>Bookmarks</h2><ul>{{range .Bookmarks}}<li><span class="muted">{{when .TS}}</span> {{.Name}}</li>{{end}}</ul>{{end}}
{{if .Truncated}}<p><b>Cut short:</b> {{range $i,$v := .Truncated}}{{if $i}}, {{end}}{{$v}}{{end}} stopped at {{.Rows}} rows.</p>{{end}}
<p class="muted">This capsule contains recorded metadata only: no packets, no Wi-Fi keys, no secrets.</p>
</body></html>`))

func (s *Server) capsule(w http.ResponseWriter, r *http.Request) {
	f, ok := s.filter(w, r)
	if !ok {
		return
	}
	f.Limit = capsuleRows
	ctx := r.Context()
	d := capsuleData{Rows: capsuleRows, From: time.UnixMilli(f.From.UnixMilli()).UTC().Format(time.RFC3339), To: time.UnixMilli(f.To.UnixMilli()).UTC().Format(time.RFC3339)}
	var err error
	if d.Summary, err = s.cfg.Store.Summary(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.Devices, err = s.cfg.Store.Devices(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.Flows, err = s.cfg.Store.Flows(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.DNS, err = s.cfg.Store.DNS(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.WiFi, err = s.cfg.Store.WiFi(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	rep, err := s.cfg.Store.Anomalies(ctx, f)
	if err != nil {
		s.fail(w, err)
		return
	}
	d.Anomalies = rep.Anomalies
	if d.Notes, err = s.cfg.Store.Annotations(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	if d.Bookmarks, err = s.cfg.Store.Bookmarks(ctx, f); err != nil {
		s.fail(w, err)
		return
	}
	for _, c := range []struct {
		name string
		n    int
	}{{"devices", len(d.Devices)}, {"connections", len(d.Flows)}, {"DNS", len(d.DNS)}, {"Wi-Fi", len(d.WiFi)}, {"notes", len(d.Notes)}, {"bookmarks", len(d.Bookmarks)}} {
		if c.n >= capsuleRows {
			d.Truncated = append(d.Truncated, c.name)
		}
	}
	// Render first: a template error must be an error, not half a report.
	var buf bytes.Buffer
	if err := capsuleTpl.Execute(&buf, d); err != nil {
		s.fail(w, err)
		return
	}
	w.Header().Set("Content-Type", "text/html; charset=utf-8")
	w.Header().Set("Content-Disposition", "attachment; filename=netgraph-capsule.html")
	_, _ = w.Write(buf.Bytes())
}
